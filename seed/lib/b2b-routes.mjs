// Turns the instance's Store API OpenAPI document into (a) the B2B route inventory recorded in
// artifacts/discovery.json and (b) the BFF route file data/b2b-routes.json.
//
// Paths are NEVER written here from memory (CLAUDE.md): they are read from the discovered document.
// This module only maps discovered operationIds to the demo's access kinds. An operationId that the
// instance does not expose is simply absent from the output.

/** operationId → BFF access kind. Only operations the demo needs; everything else stays denied. */
export const APP_B2B_OPERATIONS = Object.freeze({
  // Employee management (S9, read-only in the POC)
  readEmployees: "read",
  readEmployeesPOST: "read",
  readB2bEmployee: "read",
  readRoles: "read",
  readRolesPOST: "read",
  readRole: "read",
  readPermissions: "read",
  // Shopping lists (S8)
  readShoppingLists: "read",
  readShoppingList: "read",
  summaryShoppingList: "read",
  createShoppingList: "write",
  addLineItems: "write",
  removeLineItems: "write",
  updateLineItems: "write",
  addShoppingListsToCart: "write",
  removeShoppingLists: "write",
  // Order approval (S10)
  readApprovalRules: "read",
  listApprovalRules: "read",
  readApprovalRule: "read",
  fetchPendingOrder: "read",
  requestOrderApproval: "approval-request",
  approvePendingOrder: "approval-decide",
  declinePendingOrder: "approval-decide",
});

const METHODS = ["get", "post", "patch", "put", "delete"];

export function listOperations(openapi) {
  const ops = [];
  for (const [path, item] of Object.entries(openapi.paths ?? {})) {
    for (const m of METHODS) {
      const o = item?.[m];
      if (!o) continue;
      ops.push({
        method: m.toUpperCase(),
        path: path.replace(/^\/+/, ""),
        operationId: o.operationId ?? null,
        tags: o.tags ?? [],
        summary: o.summary ?? "",
      });
    }
  }
  return ops;
}

export const isB2B = (op) => op.tags.some((t) => /^B2B\b/.test(t));

/**
 * Any operation that creates an order (or converts something into one). The BFF must deny all of
 * these for every persona; allowlist.test.ts asserts it against data/b2b-routes.json.
 */
export function isOrderCreating(op) {
  return (
    /(^|\/)checkout\/order$/.test(op.path) ||
    /(^|\/)order$/.test(op.path) && op.method !== "GET" && !/^order$/.test(op.path) ||
    /create\w*order|order\w*create/i.test(op.operationId ?? "")
  );
}

export function buildRouteFile(ops, { shopwareVersion, discoveredAt }) {
  const routes = ops
    .filter((op) => op.operationId && APP_B2B_OPERATIONS[op.operationId])
    .filter((op) => !isOrderCreating(op))
    .map((op) => ({ id: op.operationId, method: op.method, path: op.path, kind: APP_B2B_OPERATIONS[op.operationId] }))
    .sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
  const orderCreatingRoutes = ops
    .filter(isOrderCreating)
    .map((op) => ({ method: op.method, path: op.path, operationId: op.operationId }))
    .sort((a, b) => a.path.localeCompare(b.path));
  return {
    $comment:
      "GENERATED by seed:discover from the instance's /store-api/_info/openapi3.json. Do NOT edit by hand or fill from memory (CLAUDE.md). orderCreatingRoutes must all be denied by the BFF (asserted in lib/shopware/allowlist.test.ts).",
    status: "discovered",
    discoveredAt,
    shopwareVersion,
    employeeLogin: null,
    routes,
    orderCreatingRoutes,
  };
}
