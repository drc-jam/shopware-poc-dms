#!/usr/bin/env node
// Renders data/fixture/REVIEW.md: a human-review sheet for names, prices and tiers (Phase 1 gate).
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { checkFixture } from "../seed/lib/fixture-checks.mjs";

const ROOT = path.resolve(import.meta.dirname, "..");
const site = JSON.parse(readFileSync(path.join(ROOT, "data/fixture/site-project.json"), "utf8"));
const { vehicles } = JSON.parse(readFileSync(path.join(ROOT, "data/fixture/vehicles.json"), "utf8"));
const doc = { ...site, vehicles };
const { stats, warnings } = checkFixture(doc);
const usd = (n) => "$" + n.toFixed(2);
const vName = Object.fromEntries(vehicles.map((v) => [v.key, `${v.make} ${v.model}`]));
const esc = (s) => s.replace(/\|/g, "\\|");

const lines = [];
lines.push("# Fixture review sheet", "");
lines.push("Generated by `npm run fixture:review` from `data/fixture/*.json`. Regenerate it after any edit. Edit the JSON, not this file.", "");
lines.push("**Reviewer:** ______  **Date:** ______  **Approved:** ☐", "");
lines.push("## Summary", "");
lines.push(`- ${stats.products} products: ${stats.fitmentSpecific} fitment-specific, ${stats.universal} universal`);
lines.push(`- ${stats.tiered} with dealer quantity tiers (1/5/10/25); every product has a dealer qty-1 price ≈ retail × 0.70`);
lines.push(`- ${stats.map} MAP SKUs (hide_until_cart)`);
lines.push(`- Series: ${Object.entries(stats.series).map(([k, n]) => `${k} (${n})`).join(", ")}`);
lines.push(`- ${stats.vehicles} vehicles. Makes and models are real OEMs. **Fitment is synthetic, not real OEM fitment data.**`, "");

lines.push("## Series (cross-SKU tiers, applied as cart promotions)", "");
lines.push("| Code | Label | Tiers | SKUs |", "| --- | --- | --- | --- |");
for (const s of site.series) {
  const skus = site.products.filter((p) => p.demo.series === s.code).map((p) => p.productNumber).join(", ");
  lines.push(`| ${s.code} | ${esc(s.label)} | ${s.tiers.map((t) => `${t.minQty}+ save ${t.discountPct}%`).join("; ")} | ${skus} |`);
}
lines.push("");

lines.push("## Products", "");
lines.push("| SKU | Name | Brand | Category | Retail | Dealer 1 / 5 / 10 / 25 | Series | MAP | Fits |");
lines.push("| --- | --- | --- | --- | ---: | --- | :-: | :-: | --- |");
for (const p of site.products) {
  const tiers = p.demo.dealerTiers.map((t) => usd(t.gross)).join(" / ");
  const fits = p.demo.fitment.length ? `${p.demo.fitment.length} vehicles` : "Universal";
  const map = p.demo.mapPolicy === "hide_until_cart" ? "●" : "";
  lines.push(`| ${p.productNumber} | ${esc(p.name)} | ${esc(p.brand)} | ${esc(p.categoryPath.join(" › "))} | ${usd(p.price.gross)} | ${tiers} | ${p.demo.series ?? ""} | ${map} | ${fits} |`);
}
lines.push("");

lines.push("## Vehicle coverage", "");
lines.push("| Vehicle | Years | Type | Fitting SKUs | With universal |", "| --- | --- | --- | ---: | ---: |");
for (const v of vehicles) {
  const n = stats.fittingSkusPerVehicle[v.key];
  lines.push(`| ${vName[v.key]} | ${v.yearFrom}–${v.yearTo} | ${v.type} | ${n} | ${n + stats.universal} |`);
}
lines.push("");

lines.push("## Demo people (fictional)", "");
for (const c of site.customers) lines.push(`- **${c.firstName} ${c.lastName}**: ${c.customerGroup}${c.company ? `, ${c.company}` : ""} (${c.email})`);
for (const e of site.b2b.employees) lines.push(`- **${e.firstName} ${e.lastName}**: employee, role ${e.role} (${e.email})`);
lines.push("");

lines.push("## Validator warnings", "");
lines.push(...(warnings.length ? warnings.map((w) => `- ${w}`) : ["- none"]), "");
writeFileSync(path.join(ROOT, "data/fixture/REVIEW.md"), lines.join("\n"));
console.log("wrote data/fixture/REVIEW.md");
