#!/usr/bin/env node
// Phase 0: generate lib/shopware/openapi.d.ts from the instance's Store API OpenAPI document.
// Needs SHOPWARE_STORE_API_URL + SHOPWARE_SW_ACCESS_KEY in the environment (e.g. `node --env-file=.env.local ...`).
import { writeFileSync } from "node:fs";
import path from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

const base = process.env.SHOPWARE_STORE_API_URL?.replace(/\/+$/, "");
const key = process.env.SHOPWARE_SW_ACCESS_KEY;
if (!base || !key) {
  console.error("SHOPWARE_STORE_API_URL and SHOPWARE_SW_ACCESS_KEY are required");
  process.exit(1);
}
const res = await fetch(`${base}/store-api/_info/openapi3.json`, { headers: { "sw-access-key": key, Accept: "application/json" } });
if (!res.ok) {
  console.error(`OpenAPI fetch failed: HTTP ${res.status}`);
  process.exit(1);
}
const ast = await openapiTS(await res.json());
const out = path.resolve(import.meta.dirname, "../lib/shopware/openapi.d.ts");
writeFileSync(out, `// GENERATED by npm run types:generate. Do not edit.\n${astToString(ast)}`);
console.log(`wrote ${path.relative(process.cwd(), out)}`);
